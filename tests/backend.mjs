import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRuntime} from '../modules/backend/runtime.mjs';
import {memoryRepository} from '../modules/backend/storage.mjs';
import {buildCatalog} from '../modules/backend/catalog.mjs';
import {publishProducts,manufactureBox,manufacturePack} from '../modules/backend/products.mjs';
import {createWorld} from '../modules/backend/world.mjs';
import {RARITIES} from '../modules/backend/common.mjs';

const source=JSON.parse(fs.readFileSync(new URL('../data/cards.json',import.meta.url)));
const rules={...JSON.parse(fs.readFileSync(new URL('../data/backend-rules.json',import.meta.url))),startingCash:50000};
const catalog=buildCatalog(source,rules),products=publishProducts(catalog,rules,1);
assert.equal(catalog.cards.length,2563);
const changed=buildCatalog(source,{...rules,scoring:{...rules.scoring,weights:{...rules.scoring.weights,damage:32}}});
const damageCard=catalog.cards.find(c=>c.power.vector.damage>0.5);
assert.ok(changed.byKey.get(damageCard.cardKey).globalScore>damageCard.globalScore);
assert.notEqual(changed.cards[0].ratingVersion,catalog.cards[0].ratingVersion);
for(const p of products.filter(p=>p.availability==='available')){
  const world=createWorld(rules),cards=manufactureBox(world,p).flat();
  assert.equal(cards.length,120);assert.equal(Object.values(p.boxCounts).reduce((a,b)=>a+b,0),120);
  for(const r of RARITIES)assert.equal(cards.filter(c=>c.printedRarity===r).length,p.boxCounts[r]);
  for(const packet of Array.from({length:24},(_,i)=>cards.slice(i*5,i*5+5)))assert.ok(packet.some(c=>c.printedRarity!=='N'));
  assert.ok(manufacturePack(world,p).some(c=>c.printedRarity!=='N'));
}
assert.ok(new Set(products.map(p=>JSON.stringify(p.boxCounts))).size>1,'theme composition must change product recipe');
const expensivePrices=Object.fromEntries(catalog.cards.map(c=>[c.cardKey,c.issuanceValue*100]));
const repriced=publishProducts(catalog,rules,2,expensivePrices);
assert.ok(repriced.some((p,i)=>p.prices?.box.wholesale>products[i].prices?.box.wholesale));
assert.ok(repriced.every((p,i)=>!p.prices||p.prices.box.wholesale<=products[i].prices.box.wholesale*1.16+5),'supply price influence is bounded');

const repository=memoryRepository(),host=await createRuntime({source,rules,repository});
await host.connect({contractVersion:'card-shop-ui/1.0',clientId:'backend-test'});
let serial=0;
const query=async(n,p={})=>{const r=await host.query(n,p);assert.equal(r.ok,true,JSON.stringify(r));return r.data;};
const command=async(type,payload={},extra={})=>{const r=await host.command({requestId:`test-${++serial}`,type,payload,...extra});assert.equal(r.ok,true,JSON.stringify(r));return r.data;};
await command('business.open');
const lease1=await host.pause.acquire({ownerId:'bag',reason:'背包'}),lease2=await host.pause.acquire({ownerId:'detail',reason:'详情'});
await host.advance(60);assert.equal((await query('shop.snapshot')).clock.minute,540);
await host.pause.release(lease2.leaseId);await host.advance(60);assert.equal((await query('shop.snapshot')).clock.minute,540);await host.pause.release(lease1.leaseId);
const product=products.filter(p=>p.availability==='available').sort((a,b)=>a.prices.box.wholesale-b.prices.box.wholesale)[0];
const quote=await query('products.quote',{productId:product.productId,quantity:1,unit:'box'});
const request={requestId:'order-idempotency',type:'supplier.placeOrder',quoteId:quote.quoteId,payload:{productId:product.productId,quantity:1,unit:'box'}};
const first=await host.command(request),duplicate=await host.command(request);assert.deepEqual(first,duplicate);assert.equal((await query('supplier.orders')).items.length,1);
const beforeInvalid=host.inspect();const invalid=await host.command({requestId:'invalid-quantity',type:'supplier.placeOrder',quoteId:quote.quoteId,payload:{productId:product.productId,quantity:2,unit:'box'}});assert.equal(invalid.ok,false);assert.deepEqual(host.inspect(),beforeInvalid);
for(let i=0;i<16;i++)await host.advance(1);
const order=(await query('supplier.orders')).items[0];assert.equal(order.status,'arrived');
await command('supplier.receive',{orderId:order.orderId});
const preview=await query('opening.preview',{includeBoxes:true});assert.equal(preview.cards,120);
const openingRequest={requestId:'open-idempotency',type:'opening.execute',previewId:preview.previewId,payload:{}};
assert.equal((await host.command(openingRequest)).ok,true);assert.equal((await host.command(openingRequest)).ok,true);
let items=(await query('inventory.list',{kind:'card',limit:200})).items;
assert.equal(items.length,120);assert.equal(items.reduce((n,i)=>n+i.cost,0),quote.totalDebit);
assert.ok(items.every(i=>!i.eligible),'private opening must not enter circulation');
await command('inventory.setProtection',{inventoryRef:items[0].inventoryRef,protected:true});
const surplus=await query('inventory.surplusPreview');assert.ok(surplus.quantity>0);assert.ok(!surplus.refs.includes(items[0].inventoryRef));
await command('market.listSurplus',{}, {previewId:surplus.previewId});
const listings=(await query('market.list',{limit:200})).items;assert.ok(listings.length);assert.ok(host.inspect().world.circulation[listings[0].cardKey]);
const beforeSale=(await query('shop.snapshot')).daily.goods;
for(let i=0;i<12;i++)await host.advance(1);
assert.ok((await query('shop.snapshot')).daily.goods>beforeSale);assert.ok(host.inspect().world.npcs.some(n=>Object.values(host.inspect().world.items).some(i=>i.ownerId===n.actorId&&i.kind==='card')));
const cards=(await query('inventory.list',{kind:'card',location:'collection',limit:200})).items;
const trashCard=cards.find(i=>i.available);await command('inventory.discard',{inventoryRef:trashCard.inventoryRef});
await command('business.close');await command('business.nextDay');assert.ok(!host.inspect().world.items[trashCard.inventoryRef]);
const dayOne=(await query('saves.list')).find(a=>a.day===1&&a.slot==='start');
await command('saves.load',{archiveId:dayOne.id});assert.equal((await query('shop.snapshot')).clock.day,1);assert.equal(Object.keys(host.inspect().world.items).length,0);assert.notEqual(host.inspect().world.branchId,dayOne.branchId);
await host.disconnect();
const restored=await createRuntime({source,rules,repository});await restored.connect({contractVersion:'card-shop-ui/1.0',clientId:'reconnect'});
assert.equal((await restored.command(request)).error.code,'STALE_OPERATION','old-branch success must not masquerade as a new-branch action');await restored.disconnect();
const closingWorld=createWorld(rules);closingWorld.products=products;closingWorld.clock.phase='open';closingWorld.clock.minute=1199;
const closing=await createRuntime({source,rules,repository:memoryRepository({schemaVersion:2,revision:0,world:closingWorld,archives:[],requests:{},legacyResetDone:true})});
await closing.connect({contractVersion:'card-shop-ui/1.0',clientId:'closing'});await closing.advance(1);assert.equal((await closing.query('shop.snapshot')).data.clock.phase,'closing');
assert.equal((await closing.command({requestId:'close-at-20',type:'business.close'})).ok,true);await closing.disconnect();
console.log('PASS backend: global rating, theme recipes, 26 box quotas, pause leases, order/open idempotency, atomic rejection, cost conservation, circulation, NPC purchase, trash and day branches.');
