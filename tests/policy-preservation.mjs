import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRuntime} from '../modules/backend/runtime.mjs';
import {memoryRepository} from '../modules/backend/storage.mjs';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const source=read('data/cards.json'),defaults=read('data/backend-rules.json'),repo=memoryRepository();
let host=await createRuntime({source,rules:defaults,repository:repo}),serial=0;
const connect=()=>host.connect({contractVersion:'card-shop-ui/1.0',clientId:'policy-preservation'});
const command=async(type,payload={},extra={})=>{const r=await host.command({requestId:'policy-'+ ++serial,type,payload,...extra});assert(r.ok,JSON.stringify(r.error));return r.data;};
await connect();
const product=(await host.query('products.list',{themeId:'yijiang',limit:1})).data.items[0];
const quoted=await host.query('products.quote',{productId:product.productId,unit:'pack',quantity:1});assert(quoted.ok,JSON.stringify(quoted.error));const quote=quoted.data;
await command('supplier.placeOrder',{productId:product.productId,unit:'pack',quantity:1},{quoteId:quote.quoteId});
const before=host.inspect().world,physical=JSON.stringify(before.items),order=JSON.stringify(before.orders[0]);
const initial=(await host.query('saves.days')).data.items.find(a=>a.day===1);
const custom=structuredClone(before.rules);
custom.ratingVersion+='-explicit';custom.scoring.baseline+=1;
for(const tier of custom.strengthPricing.tiers){tier.packWholesale+=5;tier.packRetail+=5;}
await command('config.apply',{configId:'backend-rules',value:custom});
assert.deepEqual(host.inspect().world.rules,custom);
assert.equal(JSON.stringify(host.inspect().world.items),physical,'配置不能重抽已封装库存');
assert.equal(JSON.stringify(host.inspect().world.orders[0]),order,'配置不能改旧订单的冻结内容/成本');
const reconnectWorld=host.inspect().world;
await host.disconnect();
host=await createRuntime({source,rules:defaults,repository:repo});await connect();
assert.deepEqual(host.inspect().world.rules,custom,'已初始化当前版本的显式规则不能在重连时被默认值覆盖');
assert.equal(JSON.stringify(host.inspect().world.items),physical);
assert.equal(JSON.stringify(host.inspect().world.orders[0]),order);
assert.equal(host.inspect().world.serial,reconnectWorld.serial,'固定发行版本不能被当成旧配盒版本反复迁移');
assert.deepEqual(host.inspect().world.log,reconnectWorld.log,'重连不能追加伪迁移日志');
assert.deepEqual(host.inspect().world.products,reconnectWorld.products,'重连不能擅自重新发布商品');
await command('saves.loadDay',{archiveId:initial.archiveId});
assert.equal(host.inspect().world.rules.ratingVersion,defaults.ratingVersion,'日初回退同步恢复规则');
assert.deepEqual(host.inspect().world.rules.strengthPricing,defaults.strengthPricing);
await host.disconnect();
console.log('PASS explicit current-version configuration survives reconnect; sealed contents and paid orders stay frozen; day-start rollback restores the recorded policy');
